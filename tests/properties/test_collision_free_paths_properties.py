            start_distance = np.sqrt(
                (start_waypoint.x - start_x)**2 + (start_waypoint.y - start_y)**2
            )
            # Allow for grid discretization error
            max_start_error = resolution * np.sqrt(2)
            assert start_distance <= max_start_error, (
                f"Start waypoint ({start_waypoint.x:.3f}, {start_waypoint.y:.3f}) "
                f"is too far from requested start ({start_x:.3f}, {start_y:.3f}): "
                f"distance {start_distance:.3f}m > {max_start_error:.3f}m"
            )
            
            # Check goal waypoint
            goal_waypoint = path.waypoints[-1]
            goal_distance = np.sqrt(
                (goal_waypoint.x - goal_x)**2 + (goal_waypoint.y - goal_y)**2
            )
            max_goal_error = resolution * np.sqrt(2)
            assert goal_distance <= max_goal_error, (
                f"Goal waypoint ({goal_waypoint.x:.3f}, {goal_waypoint.y:.3f}) "
                f"is too far from requested goal ({goal_x:.3f}, {goal_y:.3f}): "
                f"distance {goal_distance:.3f}m > {max_goal_error:.3f}m"
            )