    @given(
        dims=warehouse_dimensions(),
        robot_radius=robot_radius_strategy(),
        obstacles=st.data()
    )
    @settings(max_examples=100, deadline=60000)
    def test_path_connectivity_is_valid(self, dims, robot_radius, obstacles):
        """
        Property: For any path returned by A* planner, consecutive waypoints
        should be reachable from each other (no large gaps that would require
        the robot to teleport).
        
        **Validates: Requirements 3.1**
        """
        width, height, resolution = dims
        warehouse_map = WarehouseMap(width=width, height=height, resolution=resolution)
        
        # Add obstacles
        obstacle_config = obstacles.draw(obstacle_configuration(width, height, max_obstacles=2))
        for obs_x, obs_y, obs_width, obs_height in obstacle_config:
            warehouse_map.set_obstacle(obs_x, obs_y, obs_width, obs_height)
        
        # Generate valid positions
        try:
            positions = obstacles.draw(valid_position_pair(warehouse_map, robot_radius))
            (start_x, start_y), (goal_x, goal_y) = positions
        except:
            assume(False)
        
        # Create planner
        planner = AStarPlanner(warehouse_map, robot_radius=robot_radius, timeout_seconds=5.0)
        
        # Plan path
        path = planner.plan_path(start_x, start_y, goal_x, goal_y)
        
        if path is not None and len(path.waypoints) > 1:
            # Check connectivity between consecutive waypoints
            max_step_size = resolution * np.sqrt(2) * 2  # Allow for diagonal moves plus some margin
            
            for i in range(len(path.waypoints) - 1):
                current = path.waypoints[i]
                next_wp = path.waypoints[i + 1]
                
                distance = np.sqrt(
                    (next_wp.x - current.x)**2 + (next_wp.y - current.y)**2
                )
                
                assert distance <= max_step_size, (
                    f"Gap between waypoints {i} and {i+1} is too large: {distance:.3f}m "
                    f"(max allowed: {max_step_size:.3f}m). "
                    f"Waypoint {i}: ({current.x:.3f}, {current.y:.3f}), "
                    f"Waypoint {i+1}: ({next_wp.x:.3f}, {next_wp.y:.3f})"
                )
    
