"""
Property-based tests for collision-free paths generated by A* planner.

Feature: adaptnav-context-aware-warehouse-navigation
Property 7: Collision-Free Paths
Validates: Requirements 3.1
"""

import pytest
import numpy as np
from hypothesis import given, strategies as st, assume, settings
from adaptnav.core import WarehouseMap
from adaptnav.planning import AStarPlanner


# Custom strategies for generating test data
@st.composite
def warehouse_dimensions(draw):
    """Generate valid warehouse dimensions."""
    width = draw(st.floats(min_value=10.0, max_value=50.0))
    height = draw(st.floats(min_value=10.0, max_value=50.0))
    # Use reasonable resolution for path planning
    resolution = draw(st.floats(min_value=0.1, max_value=0.3))
    return width, height, resolution


@st.composite
def valid_position_pair(draw, warehouse_map, robot_radius):
    """Generate a pair of valid start and goal positions."""
    width = warehouse_map.width
    height = warehouse_map.height
    
    # Generate positions with sufficient margin from boundaries
    margin = robot_radius + 0.5
    
    start_x = draw(st.floats(min_value=margin, max_value=width - margin))
    start_y = draw(st.floats(min_value=margin, max_value=height - margin))
    
    goal_x = draw(st.floats(min_value=margin, max_value=width - margin))
    goal_y = draw(st.floats(min_value=margin, max_value=height - margin))
    
    # Ensure positions are collision-free
    assume(warehouse_map.is_collision_free(start_x, start_y, robot_radius))
    assume(warehouse_map.is_collision_free(goal_x, goal_y, robot_radius))
    
    # Ensure start and goal are sufficiently different
    distance = np.sqrt((goal_x - start_x)**2 + (goal_y - start_y)**2)
    assume(distance > 1.0)  # At least 1 meter apart
    
    return (start_x, start_y), (goal_x, goal_y)


@st.composite
def obstacle_configuration(draw, width, height, max_obstacles=5):
    """Generate a configuration of obstacles that doesn't block all paths."""
    num_obstacles = draw(st.integers(min_value=0, max_value=max_obstacles))
    obstacles = []
    
    for _ in range(num_obstacles):
        # Place obstacles away from edges to ensure some free space
        margin = 2.0
        obs_x = draw(st.floats(min_value=margin, max_value=width - margin))
        obs_y = draw(st.floats(min_value=margin, max_value=height - margin))
        
        # Keep obstacles reasonably sized
        obs_width = draw(st.floats(min_value=0.5, max_value=min(3.0, width * 0.2)))
        obs_height = draw(st.floats(min_value=0.5, max_value=min(3.0, height * 0.2)))
        
        obstacles.append((obs_x, obs_y, obs_width, obs_height))
    
    return obstacles


@st.composite
def robot_radius_strategy(draw):
    """Generate a valid robot radius."""
    return draw(st.floats(min_value=0.2, max_value=0.5))


@pytest.mark.property
class TestCollisionFreePathsProperties:
    """Property-based tests for collision-free paths from A* planner."""
    
    @given(
        dims=warehouse_dimensions(),
        robot_radius=robot_radius_strategy(),
        obstacles=st.data()
    )
    @settings(max_examples=100, deadline=60000)
    def test_all_path_waypoints_are_collision_free(self, dims, robot_radius, obstacles):
        """
        Property: For any valid start and goal positions in the warehouse, 
        if the A* planner returns a path, then every waypoint on that path 
        should be collision-free with respect to static obstacles 
        (minimum 0.3m clearance).
        
        **Validates: Requirements 3.1**
        """
        width, height, resolution = dims
        warehouse_map = WarehouseMap(width=width, height=height, resolution=resolution)
        
        # Add some obstacles but ensure they don't completely block the warehouse
        obstacle_config = obstacles.draw(obstacle_configuration(width, height, max_obstacles=3))
        for obs_x, obs_y, obs_width, obs_height in obstacle_config:
            warehouse_map.set_obstacle(obs_x, obs_y, obs_width, obs_height)
        
        # Generate valid start and goal positions
        try:
            positions = obstacles.draw(valid_position_pair(warehouse_map, robot_radius))
            (start_x, start_y), (goal_x, goal_y) = positions
        except:
            # Skip if we can't generate valid positions (too many obstacles)
            assume(False)
        
        # Create A* planner
        planner = AStarPlanner(warehouse_map, robot_radius=robot_radius, timeout_seconds=5.0)
        
        # Plan path
        path = planner.plan_path(start_x, start_y, goal_x, goal_y)
        
        # If planner returns a path, all waypoints must be collision-free
        if path is not None:
            assert len(path.waypoints) >= 2, "Path should have at least start and goal waypoints"
            
            # Check each waypoint for collision-free status
            for i, waypoint in enumerate(path.waypoints):
                is_free = warehouse_map.is_collision_free(
                    waypoint.x, waypoint.y, radius=robot_radius
                )
                assert is_free, (
                    f"Waypoint {i} at ({waypoint.x:.3f}, {waypoint.y:.3f}) "
                    f"is not collision-free with robot radius {robot_radius:.3f}m. "
                    f"Path has {len(path.waypoints)} waypoints."
                )
    
